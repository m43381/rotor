FEMALE_LAST_SUFFIX = {"ов": "ова", "ев": "ева", "ёв": "ёва", "ин": "ина"}
FEMALE_FIRST = ["Анна", "Мария", "Елена", "Ольга", "Наталья", "Екатерина", "Татьяна", "Ирина"]
FEMALE_PATRONYMIC = [p.removesuffix("ич") + "на" for p in PATRONYMIC]


@dataclass(frozen=True)
class Fio:
    last: str
    first: str
    middle: str


def fio(rng: random.Random, female_share: float = 0.08) -> Fio:
    last = rng.choice(MALE_LAST)
    if rng.random() < female_share:
        for suffix, female in FEMALE_LAST_SUFFIX.items():
            if last.endswith(suffix):
                last = last.removesuffix(suffix) + female
                break
        return Fio(last, rng.choice(FEMALE_FIRST), rng.choice(FEMALE_PATRONYMIC))
    return Fio(last, rng.choice(MALE_FIRST), rng.choice(PATRONYMIC))
